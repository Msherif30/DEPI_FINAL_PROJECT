-- ============================================================================
-- RestoMate AI - remove data created during development verification
-- ============================================================================
-- Purpose
--   The live `bremer` database was seeded with 41 orders / 150 order items /
--   30 customers. During browser and API acceptance testing, a handful of
--   extra rows were created (orders 42-48, test kiosk sessions, test payments,
--   audit rows, login sessions and one auto-created customer profile).
--
--   This script removes ONLY those verification artifacts so the delivered
--   database matches the original seed again. It never touches rows 1-41 and
--   never drops or recreates a table.
--
-- Safety
--   * Take a backup first:
--       mysqldump -uroot -p --databases bremer --single-transaction \
--         --result-file=database/backups/bremer_before_cleanup.sql
--   * Run inside the transaction below and verify the counts afterwards.
--   * Review the WHERE clauses before running on any other environment.
-- ============================================================================

START TRANSACTION;

-- Kiosk conversations and carts (tables introduced by migration 003/004).
DELETE FROM kiosk_cart_items;
DELETE FROM kiosk_messages;
UPDATE kiosk_sessions SET order_id = NULL WHERE order_id BETWEEN 42 AND 48;
DELETE FROM kiosk_sessions;

-- Order lifecycle rows for the seven verification orders.
DELETE FROM order_stock_applications WHERE order_id BETWEEN 42 AND 48;
DELETE FROM stock_movements WHERE order_id BETWEEN 42 AND 48;
DELETE FROM order_status_history WHERE order_id BETWEEN 42 AND 48;
DELETE FROM payments WHERE order_id BETWEEN 42 AND 48;
DELETE FROM order_items WHERE order_id BETWEEN 42 AND 48;
DELETE FROM orders WHERE order_id BETWEEN 42 AND 48;

-- Audit rows and login sessions generated by the test runs.
DELETE FROM audit_logs;
DELETE FROM user_sessions;

-- Customer profiles auto-created for test accounts during verification
-- (a customer-role account gets a profile on first use of the customer
-- portal). The original 30 historical customers have customer_id 1-30 and
-- no user_id, so they are always preserved.
DELETE FROM customers
WHERE customer_id > 30
  AND user_id IS NOT NULL
  AND created_at >= '2026-11-12 00:00:00';

COMMIT;

-- Expected result after running:
--   orders            41
--   order_items      150
--   customers         30
--   payments           0
--   order_status_history 0
--   kiosk_sessions     0
--   audit_logs         0
